def idf_candidates(repo, given=None):
    """Folders with an export.sh that could be an ESP-IDF, the explicitly named one first."""
    def ex(p):
        return os.path.abspath(os.path.expanduser(p))
    raw = []
    if given:
        raw.append(given)
    else:
        raw += [os.environ.get("SQUIRREL_IDF"), os.environ.get("IDF_PATH")]
        for base in (os.path.join(repo, ".."), os.path.join(repo, "..", ".."), repo, "~", "~/esp", "~/src"):
            raw += sorted(glob.glob(os.path.join(ex(base), "esp-idf*")))
        raw += sorted(glob.glob(ex("~/esp/*/esp-idf")))
    out = []
    for r in raw:
        if r and os.path.isfile(os.path.join(ex(r), "export.sh")) and ex(r) not in out:
            out.append(ex(r))
    return out


def idf_version(idf):
    try:
        with open(os.path.join(idf, "version.txt")) as f:
            return f.read().strip()
    except OSError:
        pass
    try:
        out = subprocess.run(["git", "-C", idf, "describe", "--tags"], capture_output=True, text=True, timeout=10)
        return out.stdout.strip() if out.returncode == 0 else ""
    except (OSError, subprocess.SubprocessError):
        return ""


def idf_ok(version):
    """ESP-IDF 5.4.x only: this firmware is built and patched for it (and on 5.5 the board's microphone returns silence)."""
    m = re.match(r"v?(\d+)\.(\d+)", version or "")
    return bool(m) and (int(m.group(1)), int(m.group(2))) == (5, 4)


def choose_idf(repo, given=None, allow_any=False):
    """(path, version) of the ESP-IDF to use. Raises BuildError if there is no 5.4.x (unless allow_any)."""
    found = [(p, idf_version(p)) for p in idf_candidates(repo, given)]
    good = [f for f in found if idf_ok(f[1])]
    if good:
        return good[0]
    if allow_any and found:
        say(f"  warning: using ESP-IDF {found[0][1] or '?'} although 5.4.x is expected (--allow-any-idf)")
        return found[0]
    if found:
        listing = "\n".join(f"    {p}  {v or '(version unknown)'}" for p, v in found)
        raise BuildError("No ESP-IDF 5.4.x found. This firmware is built (and its patches are made) for 5.4.2. Found:\n" + listing
                         + "\n  Install the right one next to it:  python3 build_firmware.py --install-idf\n"
                         + "  (or by hand: " + f"git clone --depth 1 --branch {IDF_WANTED} {IDF_URL}; git submodule update --init --recursive; ./install.sh esp32s3)")
    raise BuildError("ESP-IDF not found" + (f" at {given}" if given else "") + ". Install v5.4.2:  python3 build_firmware.py --install-idf\n"
                     "  or point to an existing 5.4.x with --idf /path/to/esp-idf (the folder with export.sh).")


def board_type(makefile_path, board):
    """The BOARD_TYPE the firmware's Makefile gives a board (its `boards :=` list: `M5STACK_CardputerADV:cardputeradv`), or None."""
    try:
        with open(makefile_path, encoding="utf-8") as f:
            text = f.read()
    except OSError:
        return None
    m = re.search(r"^[ \t]*" + re.escape(board) + r":([\w\-]+)[ \t]*\\?[ \t]*$", text, re.M)
    return m.group(1) if m else None


def find_mpy_cross(repo):
    for rel in (("micropython", "mpy-cross", "build", "mpy-cross"), ("micropython", "mpy-cross", "mpy-cross")):
        p = os.path.join(repo, *rel)
        if os.path.isfile(p) and os.access(p, os.X_OK):
            return p
    return shutil.which("mpy-cross")


def compile_check(mpy_cross, stage_dir, keep_dir=None):
    """Compile every staged file with the firmware's own mpy-cross. Returns ([errors], total .mpy bytes)."""
    errors, total = [], 0
    work = keep_dir or os.path.join(STATE, "mpy_check")
    if os.path.isdir(work):
        shutil.rmtree(work)
    for root, _dirs, files in os.walk(stage_dir):
        for name in sorted(files):
            if not name.endswith(".py"):
                continue
            src = os.path.join(root, name)
            rel = os.path.relpath(src, stage_dir)
            out = os.path.join(work, rel[:-3] + ".mpy")
            os.makedirs(os.path.dirname(out), exist_ok=True)
            res = subprocess.run([mpy_cross, "-o", out, "-s", rel, src], capture_output=True, text=True)
            if res.returncode != 0:
                errors.append(f"{rel}: {(res.stderr or res.stdout).strip()[:300]}")
            elif os.path.exists(out):
                total += os.path.getsize(out)
    return errors, total


def make_board(repo, base, new, stage_dir):
    """Create m5stack/boards/<new> as a copy of <base> + the frozen sources. Never touches an existing, foreign board."""
    boards = os.path.join(repo, "m5stack", "boards")
    src, dst = os.path.join(boards, base), os.path.join(boards, new)
    if not os.path.isdir(src):
        raise BuildError(f"base board {base} not found in {boards}\n  Available: {', '.join(sorted(os.listdir(boards))[:12])} ...")
    manifest_src = os.path.join(src, "manifest.py")
    if not os.path.isfile(manifest_src):
        raise BuildError(f"{manifest_src} does not exist - this tool needs a board with its own manifest.py")
    if os.path.exists(dst):
        if not os.path.exists(os.path.join(dst, GENERATED_MARK)):
            raise BuildError(f"{dst} exists and was not made by this tool - not touching it. Pick another --board name.")
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "build*"))
    for root, _dirs, files in os.walk(dst):
        for name in files:
            if name.endswith(".py"):
                continue
            path = os.path.join(root, name)
            try:
                with open(path, encoding="utf-8") as f:
                    text = f.read()
            except (UnicodeDecodeError, OSError):
                continue
            if base in text:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text.replace(base, new))
    shutil.copytree(stage_dir, os.path.join(dst, "squirrel"), ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    manifest = os.path.join(dst, "manifest.py")
    with open(manifest, encoding="utf-8") as f:
        text = f.read()
    text = text.rstrip("\n") + "\n\n" + MANIFEST_BEGIN + '\nfreeze("$(BOARD_DIR)/squirrel")\n'
    with open(manifest, "w", encoding="utf-8") as f:
        f.write(text)
    with open(os.path.join(dst, GENERATED_MARK), "w") as f:
        f.write("generated by build_firmware.py\n")
    return dst


def expand_vars(text, repo, board_dir):
    if repo:
        text = (text.replace("$(MPY_DIR)", os.path.join(repo, "micropython"))
                    .replace("$(MPY_LIB_DIR)", os.path.join(repo, "micropython", "lib", "micropython-lib"))
                    .replace("$(PORT_DIR)", os.path.join(repo, "micropython", "ports", "esp32")))
    return text.replace("$(BOARD_DIR)", board_dir)


def manifest_refs(board_dir, repo=None):
    """[(name as written, absolute path)] of the .py files a board's manifest.py names."""
    try:
        with open(os.path.join(board_dir, "manifest.py"), encoding="utf-8") as f:
            text = f.read().split(MANIFEST_BEGIN)[0]
    except OSError:
        return []
    out = []
    for line in text.split("\n"):
        if line.strip().startswith("#"):
            continue
        strings = re.findall(r"""["']([^"']+)["']""", line)
        m = re.search(r"""base_path\s*=\s*["']([^"']+)["']""", line)
        base = m.group(1) if m else None
        if base is not None:
            pairs = [(base, x) for x in strings if x != base and x.endswith((".py", ".mpy"))]
        elif line.strip().startswith("freeze(") and len(strings) >= 2:
            pairs = [(strings[0], x) for x in strings[1:] if x.endswith((".py", ".mpy"))]
        else:
            pairs = [("", x) for x in strings if x.endswith((".py", ".mpy"))]
        for folder, name in pairs:
            path = expand_vars(os.path.join(folder, name) if folder else name, repo, board_dir)
            if "$(" in path:
                continue
            if not os.path.isabs(path):
                path = os.path.join(board_dir, path)
            out.append((name, os.path.normpath(path)))
    return out


def manifest_missing_refs(board_dir, repo=None):
    seen, missing = set(), []
    for name, path in manifest_refs(board_dir, repo):
        if not os.path.exists(path) and path not in seen:
            seen.add(path)
            missing.append((name, path))
    return missing


def manifest_missing_files(board_dir, repo=None):
    return [name for name, _path in manifest_missing_refs(board_dir, repo)]


def makefile_target_for(text, rel):
    variables = {m.group(1) for m in re.finditer(r"^[ \t]*(\w+)[ \t]*[:?+]?=[ \t]*" + re.escape(rel) + r"[ \t]*$", text, re.M)}
    needles = {rel} | {"$(%s)" % v for v in variables} | {"${%s}" % v for v in variables}
    if re.search(r"^" + re.escape(rel) + r"[ \t]*:(?![=:])", text, re.M):
        return rel
    target = None
    for line in text.split("\n"):
        if line.startswith("\t"):
            if target and any(re.search(r"(?:>>?|\btouch\b|\btee\b(?:\s+-a)?|\s-o|--output(?:=|\s))\s*['\"]?" + re.escape(n), line) for n in needles):
                return target
            continue
        m = re.match(r"^([A-Za-z0-9_.\-]+)[ \t]*:(?![=:])", line)
        if m:
            target = m.group(1)
        elif line.strip() and not re.match(r"^[ \t]*(ifeq|ifneq|ifdef|ifndef|else|endif|#)", line):
            target = None
    return None


def generate_missing(repo, base, idf, type_arg=""):
    m5 = os.path.join(repo, "m5stack")
    base_dir = os.path.join(m5, "boards", base)
    made, failed, elsewhere = [], [], []
    try:
        with open(os.path.join(m5, "Makefile"), encoding="utf-8") as f:
            makefile = f.read()
    except OSError:
        makefile = ""
    for name, path in manifest_missing_refs(base_dir, repo):
        if not path.startswith(base_dir + os.sep):
            elsewhere.append(name)
            continue
        rel = os.path.relpath(path, m5)
        target = makefile_target_for(makefile, rel) or rel
        how = "a rule for the file" if target == rel else f"the target `{target}`, whose recipe writes it - and only for BOARD={base}"
        say(f"  {name} is named by the manifest of {base} and does not exist yet: asking the Makefile to make it  (make {target}: {how})")
        code = bash(idf_prefix(idf) + f"make BOARD={base}{type_arg} {target}", cwd=m5)
        (made if code == 0 and os.path.exists(path) else failed).append(name)
    return made, failed, elsewhere


def git_exclude(repo, new):
    path = os.path.join(repo, ".git", "info", "exclude")
    line = f"m5stack/boards/{new}/"
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        existing = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if line not in existing.split("\n"):
            with open(path, "a", encoding="utf-8") as f:
                f.write(("" if existing.endswith("\n") or not existing else "\n") + line + "\n")
            return True
    except OSError:
        pass
    return False


