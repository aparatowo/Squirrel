    say("tools       : " + tools)
    if not shutil.which("quilt"):
        say("  quilt is missing: `make patch` needs it ->  sudo apt install quilt")
        problems += 1
    say("\n" + ("everything needed is in place" if not problems else f"{problems} thing(s) to fix before a build"))
    return 1 if problems else 0


