def font_into_image(repo):
    """Copy the app's font where `make` packs the system file system.  Returns the copy (removed after the build),
    or None: no font here, or a file of that name is already there (then it is left alone and used)."""
    font = find_font(HERE)
    if font is None:
        say("font       : none found (fonts/" + FONT_NAME + " or " + FONT_NAME + ") - the image has no Polish letters")
        return None
    folder = os.path.join(repo, *FONT_IN_REPO)
    target = os.path.join(folder, FONT_NAME)
    if os.path.exists(target):
        say(f"font       : {target} already exists - packed as it is")
        return None
    os.makedirs(folder, exist_ok=True)
    shutil.copyfile(font, target)
    say(f"font       : {os.path.relpath(font, HERE)} ({os.path.getsize(font)} bytes) goes into the image -> {FONT_ON_DEVICE}")
    return target


