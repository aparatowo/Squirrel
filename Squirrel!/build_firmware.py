def prepare_sources(app_dir, verbose=True, exclude=(), prefer=None, port=DEFAULT_PORT):
    hint = wrong_folder_hint(app_dir)
    if hint:
        raise BuildError(hint)
    left_out, off = port_excludes(port, app_dir)
    # a screen may also lie flat next to the sources (layout_for_firmware moves it into screens/): leave that copy out too
    left_out |= {m[len("screens/"):] for m in left_out if m.startswith("screens/")}
    sources = find_sources(app_dir, tuple(exclude) + tuple(sorted(left_out)) + (PORT_CONFIG,))
    if not sources:
        raise BuildError(f"no .py files found in {app_dir}")
    staged, warnings = layout_for_firmware(sources, prefer)
    gone = {m.rsplit("/", 1)[-1][:-3] for m in left_out}         # modules left out on purpose: no warning about them
    warnings = [w for w in warnings if not any(f"screens.{g}," in w or f" {g}.py" in w for g in gone)]
    staged[PORT_CONFIG] = write_port_config(port, os.path.join(STATE, "port"))     # always fresh from port.toml
    if verbose:
        say(f"port: {port}" + (f"  (not built: {', '.join(f'{k} - {v}' for k, v in sorted(off.items()))})" if off else "  (every feature)"))
    errors, more = check_imports(staged)
    more = [w for w in more if not any(f"imports '{g}'" in w for g in gone)]
    if verbose:
        say(f"sources: {len(staged)} modules ({sum(1 for p in staged if p.startswith('screens/'))} of them screens)")
        for w in warnings + more:
            say("  warning: " + w)
        for e in errors:
            say("  ERROR: " + e)
    if errors:
        raise BuildError("the sources do not hang together (see ERROR lines above)")
    if "squirrel_boot.py" not in staged:
        raise BuildError("squirrel_boot.py is missing from the folder: /flash/main.py needs it")
    if "squirrel_app.py" not in staged:
        raise BuildError("squirrel_app.py is missing from the folder")
    return staged


