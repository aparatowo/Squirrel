def git_short(path):
    try:
        out = subprocess.run(["git", "-C", path, "rev-parse", "--short", "HEAD"], capture_output=True, text=True, timeout=10)
        return out.stdout.strip() if out.returncode == 0 else ""
    except (OSError, subprocess.SubprocessError):
        return ""


def stage(staged, stage_dir, build_id, app_dir):
    """Copy the sources into stage_dir (fresh), add screens/__init__.py and sq_info.py. Returns the file list."""
    if os.path.isdir(stage_dir):
        shutil.rmtree(stage_dir)
    os.makedirs(stage_dir)
    files = []
    for rel, absolute in sorted(staged.items()):
        target = os.path.join(stage_dir, *rel.split("/"))
        os.makedirs(os.path.dirname(target), exist_ok=True)
        shutil.copyfile(absolute, target)
        with open(absolute, "rb") as f:
            data = f.read()
        files.append((rel, len(data), zlib.crc32(data) & 0xFFFFFFFF))
    if any(rel.startswith("screens/") for rel in staged):        # a frozen package needs its __init__.py
        init = os.path.join(stage_dir, "screens", "__init__.py")
        if not os.path.exists(init):
            open(init, "w").close()
    font = find_font(app_dir)
    info = SQ_INFO.format(build=build_id, git=git_short(app_dir), files=tuple(files),
                          font_size=os.path.getsize(font) if font else 0)
    with open(os.path.join(stage_dir, "sq_info.py"), "w", encoding="utf-8") as f:
        f.write(info)
    return files


