class RawRepl:
    """MicroPython's raw REPL over a serial port, with the standard library only (termios: Linux / macOS)."""

    def __init__(self, port, lines_low=False):
        """lines_low: drop DTR and RTS after opening - a board with the classic auto-reset circuit on a USB-serial chip
        (the T-Watch: CH9102) is otherwise held in reset.  Not for native USB (the Cardputer's S3), where it is not needed."""
        import termios
        import tty
        self.fd = os.open(port, os.O_RDWR | os.O_NOCTTY | os.O_NONBLOCK)
        self._buf = b""                               # read but not consumed yet
        tty.setraw(self.fd)
        attrs = termios.tcgetattr(self.fd)
        attrs[4] = attrs[5] = termios.B115200
        termios.tcsetattr(self.fd, termios.TCSANOW, attrs)
        if lines_low:
            import fcntl
            import struct
            fcntl.ioctl(self.fd, termios.TIOCMBIC, struct.pack("I", termios.TIOCM_DTR | termios.TIOCM_RTS))

    def close(self):
        try:
            os.close(self.fd)
        except OSError:
            pass

    def write(self, data):
        """Write everything, waiting while the port's buffer is full (a UART at 115200 is slower than we write)."""
        import select
        view = memoryview(data)
        while view:
            try:
                n = os.write(self.fd, view[:256])
                view = view[n:]
            except BlockingIOError:
                select.select([], [self.fd], [], 1)

    def _read_n(self, n, seconds=5):
        import select
        end = time.time() + seconds
        while len(self._buf) < n:
            if time.time() >= end:
                raise BuildError(f"the device stopped answering (raw-paste, got {self._buf!r})")
            if select.select([self.fd], [], [], 0.1)[0]:
                try:
                    self._buf += os.read(self.fd, 4096)
                except OSError:
                    pass
        out, self._buf = self._buf[:n], self._buf[n:]
        return out

    def submit(self, code):
        """Send `code` to the raw REPL for execution; afterwards its output, Ctrl-D, its error text, Ctrl-D follow.

        Uses MicroPython's raw-paste mode (the device paces us: no byte is lost on a slow UART, the way mpremote does it);
        a firmware without it gets the code in one piece and answers "OK" first."""
        data = code.encode()
        self.write(b"\x05A\x01")
        try:
            answer = self._read_n(2)
        except BuildError:
            answer = b""
        if answer != b"R\x01":                     # no raw-paste mode: start the raw REPL afresh, send in one piece
            self.enter()
            self.write(data + b"\x04")
            self.read_until(b"OK", 10)
            return
        window = self._read_n(2)
        window = window[0] | window[1] << 8
        left, i = window, 0
        import select
        while i < len(data):
            while left == 0 or select.select([self.fd], [], [], 0)[0]:
                c = self._read_n(1, 10)
                if c == b"\x01":
                    left += window
                elif c == b"\x04":                  # the device ended the paste early (an error while receiving)
                    self.write(b"\x04")
                    return
                else:
                    raise BuildError(f"unexpected {c!r} from the device during raw-paste")
            chunk = data[i:i + left]
            self.write(chunk)
            left -= len(chunk)
            i += len(chunk)
        self.write(b"\x04")
        self.read_until(b"\x04", 10)               # the device's "end of data" acknowledgement

    def _drain(self):
        """Forget what the device printed so far (the app's output, the Ctrl-C traceback)."""
        try:
            while True:
                if not os.read(self.fd, 4096):
                    break
        except OSError:                               # nothing more to read (non-blocking)
            pass
        self._buf = b""

    def read_until(self, marker, seconds):
        """Everything up to and including `marker`; what came after it stays for the next call."""
        import select
        end = time.time() + seconds
        while marker not in self._buf:
            if time.time() >= end:
                got, self._buf = self._buf, b""
                raise BuildError(f"the device did not answer (waited {seconds} s for {marker!r}; got {got[-200:]!r})")
            ready, _w, _x = select.select([self.fd], [], [], 0.1)
            if ready:
                try:
                    self._buf += os.read(self.fd, 4096)
                except OSError:
                    pass
        cut = self._buf.index(marker) + len(marker)
        out, self._buf = self._buf[:cut], self._buf[cut:]
        return out

    def enter(self):
        """Stop whatever runs (Ctrl-C - the app ends with "Stopped by user") and switch to the raw REPL."""
        for _ in range(3):
            self.write(b"\r\x03\x03")
            time.sleep(0.4)
            self._drain()
            self.write(b"\x01")
            try:
                self.read_until(b"raw REPL; CTRL-B to exit\r\n>", 3)
                return
            except BuildError:
                continue
        raise BuildError("no MicroPython REPL on the port (is Thonny or another terminal holding it?)")

    def run(self, code):
        """Execute `code`; returns what it printed.  Raises with the device's traceback if it failed."""
        self.submit(code)
        out = self.read_until(b"\x04", 20)
        err = self.read_until(b"\x04", 5)
        printed, failed = out[:-1].decode(errors="replace"), err[:-1].decode(errors="replace").strip()
        if failed:
            raise BuildError("the device reported an error:\n" + failed)
        return printed

    def reset(self):
        try:
            self.write(b"import machine\nmachine.reset()\n\x04")
        except OSError:
            pass


_STEP_TEXT = {
    "MAIN": {"ok": "/flash/main.py is the launcher already", "written": "/flash/main.py written (the launcher, device/main.py)",
             "replaced": "/flash/main.py replaced by the launcher (the old one is kept as /flash/main.py.old)"},
    "BOOT": {"ok": "/flash/boot.py left as it is", "none": "no /flash/boot.py (nothing to do)",
             "renamed": "UIFlow's /flash/boot.py (imports `startup`, which this firmware has not) renamed to /flash/boot.py.uiflow"},
}


def setup_device(port, machine):
    """Prepare the device on `port` for Squirrel! (see _DEVICE_SETUP) and restart it.  Returns 0."""
    with open(os.path.join(HERE, DEVICE_MAIN), "rb") as f:
        launcher = f.read()
    if not machine:
        raise BuildError("the port's port.toml has no [port] machine - without it the device cannot be recognised, so it is not touched")
    say(f"== preparing the device on {port} for Squirrel!")
    repl = RawRepl(port)
    try:
        repl.enter()
        printed = repl.run(f"WANT = {machine!r}\nLAUNCHER = {launcher!r}\n" + _DEVICE_SETUP)
        lines = [l.strip().split("|") for l in printed.splitlines() if "|" in l]
        if lines and lines[0][0] == "WRONG":
            repl.write(b"\x02")
            raise BuildError(f"the device on {port} is {lines[0][1]!r}, not a {machine} - not touched")
        changed = False
        for parts in lines:
            key, what = parts[0], parts[1]
            if key == "MACHINE":
                say(f"  device: {what}")
            elif key in _STEP_TEXT:
                say("  " + _STEP_TEXT[key][what])
                changed |= what not in ("ok", "none")
            elif key == "OPTION":
                if what == "set":
                    say(f"  UIFlow boot option set to 0 = run main.py directly (it was {parts[2]})")
                    changed = True
                elif what == "ok":
                    say("  UIFlow boot option is 0 (run main.py directly) already")
                else:
                    say(f"  WARNING: the UIFlow boot option could not be set: {parts[2]}")
        say("  restarting the device" + ("" if changed else " (nothing had to be changed)"))
        repl.reset()
    finally:
        repl.close()
    say("device ready: Squirrel! starts.  Check with Thonny:  import sq_info; sq_info.report()")
    return 0


def cmd_setup_device(args):
    port = args.setup_device
    if not os.path.exists(port):
        raise BuildError(f"{port} does not exist (ls /dev/ttyACM*)")
    name = args.port or DEFAULT_PORT
    return setup_device(port, load_port(name).get("port", {}).get("machine"))


def flash(image, kind, port, idf, prepare=True, machine=None):
    if kind != "complete":
        raise BuildError("refusing to flash: this is not a complete image (see above)")
    say(FLASH_WARNING)
    where = f'-p "{port}" ' if port else ""
    say(f"== flashing {image}" + (f" to {port}" if port else " (esptool looks for the port itself)"))
    # --before no_reset first: a device already in download mode (G0 held while plugging in) must NOT be reset - the
    # reset makes it leave download mode, its USB port vanishes for a moment and esptool cannot open it.  Only if that
    # finds no bootloader (the app is running) is the usual reset into download mode tried.
    # --after watchdog_reset: the usual reset through RTS leaves an S3 on its USB-Serial/JTAG port in the bootloader
    # ("waiting for download"); a reset by the RTC watchdog starts the new firmware.
    base = idf_prefix(idf) + f'python -m esptool --chip esp32s3 {where}-b 460800 --after watchdog_reset'
    code = bash(f'{base} --before no_reset write_flash 0x0 "{image}"')
    if code != 0:
        say("  no bootloader answered without a reset (the app is running?) - trying again with a reset into download mode")
        if port:
            wait_for_port(port)
        code = bash(f'{base} --before default_reset write_flash 0x0 "{image}"')
    if code != 0:
        raise BuildError("flashing failed. Close Thonny (it holds the port); hold G0 while plugging the USB cable to enter the bootloader;\n"
                         "  if the port is refused: sudo usermod -aG dialout $USER and log in again.")
    if not port:
        say("flashed. Now prepare the device (main.py, boot.py, boot option):  python3 build_firmware.py --setup-device PORT")
        return 0
    if not prepare:
        say(f"flashed. --no-device-setup: the device was not prepared; later:  python3 build_firmware.py --setup-device {port}")
        return 0
    say("flashed. Waiting for the device to start ...")
    if not wait_for_port(port, 20):
        raise BuildError(f"{port} did not come back after flashing - run  python3 build_firmware.py --setup-device PORT  once it is there")
    time.sleep(3)                                      # the firmware's own start-up, before the REPL answers
    return setup_device(port, machine)


def cmd_flash_image(args):
    c = load_config(args)
    path = args.flash_image
    if not os.path.isfile(path) and os.path.isfile(os.path.join(DIST, path)):
        path = os.path.join(DIST, path)
    if not os.path.isfile(path):
        raise BuildError(f"{args.flash_image} not found (looked in the current folder and in {DIST})")
    path = os.path.abspath(path)
    kind = classify_image(path)
    say(f"image {path}: {os.path.getsize(path)} bytes, {kind}")
    repo = locate_repo(c["repo"])
    idf, _version = choose_idf(repo, c["idf"], allow_any=True)
    return flash(path, kind, args.flash, idf, prepare=not args.no_device_setup, machine=c["machine"])


