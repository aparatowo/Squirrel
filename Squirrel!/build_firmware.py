def load_toml(path):
    try:
        import tomllib
    except ImportError:
        raise BuildError(f"reading {os.path.basename(path)} needs Python 3.11 or newer (tomllib); this is {sys.version.split()[0]}")
    try:
        with open(path, "rb") as f:
            return tomllib.load(f)
    except OSError as e:
        raise BuildError(f"cannot read {path}: {e}")
    except tomllib.TOMLDecodeError as e:
        raise BuildError(f"{path}: {e}")


def port_names(app_dir=HERE):
    folder = os.path.join(app_dir, PORTS_DIR)
    if not os.path.isdir(folder):
        return []
    return sorted(d for d in os.listdir(folder) if os.path.isfile(os.path.join(folder, d, "port.toml")))


def load_port(name, app_dir=HERE):
    path = os.path.join(app_dir, PORTS_DIR, name, "port.toml")
    if not os.path.isfile(path):
        raise BuildError(f"no port called {name!r}: {path} does not exist.  Ports here: {', '.join(port_names(app_dir)) or '-'}")
    port = load_toml(path)
    if port.get("port", {}).get("name") != name:
        raise BuildError(f"{path}: [port] name must be {name!r} (the folder's name)")
    return port


def _present(table):
    return isinstance(table, dict) and table.get("installed", True) is not False and table.get("enabled", True) is not False


def hardware_of(port):
    """The set of what the port has: every enabled section ("audio_in", "signal.led") and every key that is true in it
    ("input.keyboard", "radio.wifi")."""
    found = set()

    def walk(table, path):
        for key, value in table.items():
            sub = path + "." + key if path else key
            if isinstance(value, dict):
                if _present(value):
                    found.add(sub)
                    walk(value, sub)
            elif value is True and path and key not in ("installed", "enabled"):
                found.add(sub)

    walk({k: v for k, v in port.items() if k not in _NOT_HARDWARE}, "")
    return found


def resolve_features(port, registry):
    """({feature built}, {feature not built: why}).  Raises when port.toml switches on a feature its hardware cannot do,
    or names a feature features.toml does not know."""
    hardware = hardware_of(port)
    wanted = port.get("features", {})
    unknown = sorted(set(wanted) - set(registry))
    if unknown:
        raise BuildError(f"[features] of port {port['port']['name']} names {', '.join(unknown)} - not in {FEATURES_FILE} "
                         f"(known: {', '.join(sorted(registry))})")
    on, off = set(), {}
    for name, feature in registry.items():
        missing = [r for r in feature.get("requires", ()) if r not in hardware]
        choice = wanted.get(name)
        if choice is False:
            off[name] = "switched off in port.toml"
        elif missing:
            if choice is True:
                raise BuildError(f"port {port['port']['name']} switches on {name}, which needs {', '.join(missing)} - not in its port.toml")
            off[name] = "needs " + ", ".join(missing)
        else:
            on.add(name)
    return on, off


def _const_name(path):
    return re.sub(r"[^A-Za-z0-9]", "_", "_".join(path)).upper()


def flatten_port(port):
    """[(CONSTANT, value)] of every key of port.toml, in file order ([features] left out: it becomes FEATURES)."""
    out = []

    def walk(table, path):
        for key, value in table.items():
            if isinstance(value, dict):
                walk(value, path + [key])
            else:
                out.append((_const_name(path + [key]), tuple(value) if isinstance(value, list) else value))

    walk({k: v for k, v in port.items() if k != "features"}, [])
    return out


def port_drivers(port):
    """{driver module name} the port names (every `driver = "..."`): drivers/<name>.py."""
    names = set()

    def walk(table):
        for key, value in table.items():
            if isinstance(value, dict):
                if _present(value):
                    walk(value)
            elif key == "driver" and isinstance(value, str):
                names.add(value)

    walk(port)
    return names


def check_port(port, app_dir=HERE):
    """Errors in port.toml that would only show on the device."""
    name = port["port"]["name"]
    errors = []
    for section in ("port", "display", "storage"):
        if section not in port:
            errors.append(f"port {name}: [{section}] is missing")
    for key in ("width", "height", "driver"):
        if key not in port.get("display", {}):
            errors.append(f"port {name}: [display] {key} is missing")
    if "base_dir" not in port.get("storage", {}):
        errors.append(f"port {name}: [storage] base_dir is missing")
    for driver in sorted(port_drivers(port)):
        if not os.path.isfile(os.path.join(app_dir, "drivers", driver + ".py")):
            errors.append(f"port {name}: driver {driver!r} - there is no drivers/{driver}.py")
    if not os.path.isfile(os.path.join(app_dir, PORTS_DIR, name, "board.py")):
        errors.append(f"port {name}: {PORTS_DIR}/{name}/board.py is missing")
    if errors:
        raise BuildError("\n  ".join(errors))


def render_port_config(name, app_dir=HERE):
    """The text of port_config.py for port `name` - the device-side copy of its port.toml."""
    port = load_port(name, app_dir)
    check_port(port, app_dir)
    registry = load_toml(os.path.join(app_dir, FEATURES_FILE))
    on, off = resolve_features(port, registry)

    def hidden(kind):
        return sorted({item for f in off for item in registry[f].get(kind, ())})

    def fs(items):
        return "frozenset((" + "".join(repr(i) + ", " for i in sorted(items)) + "))"

    lines = [
        f"# port_config.py - the port this firmware is built for: {port['port'].get('title', name)}",
        f"#",
        f"# GENERATED by build_firmware.py from {PORTS_DIR}/{name}/port.toml and {FEATURES_FILE} - do not edit; after a change",
        f"# there:  python3 build_firmware.py --gen-port-config [--port NAME]   (a build regenerates it by itself)",
        f"",
        f"PORT = {name!r}",
        f"BOARD_MODULE = {PORTS_DIR + '.' + name + '.board'!r}",
        f"HARDWARE = {fs(hardware_of(port))}",
        f"FEATURES = {fs(on)}",
        f"# what the app hides because a feature is not built (features.toml)",
        f"HIDDEN_MENUS = {fs(hidden('menus'))}",
        f"HIDDEN_SCREENS = {fs(hidden('screens'))}",
        f"HIDDEN_ACTIONS = {fs(hidden('actions'))}",
        f"HIDDEN_GROUPS = {fs(hidden('settings'))}",
        f"",
    ]
    section = None
    for const, value in flatten_port(port):
        head = const.split("_")[0]
        if head != section:
            section = head
            lines.append("")
        lines.append(f"{const} = {value!r}")
    return "\n".join(lines) + "\n"


def port_excludes(name, app_dir=HERE):
    """Relative paths of the sources a build for port `name` leaves out: the modules of features that are not built,
    the drivers it does not name, the folders of the other ports."""
    port = load_port(name, app_dir)
    registry = load_toml(os.path.join(app_dir, FEATURES_FILE))
    _on, off = resolve_features(port, registry)
    out = {m for f in off for m in registry[f].get("modules", ())}
    used = port_drivers(port)
    folder = os.path.join(app_dir, "drivers")
    if os.path.isdir(folder):
        out |= {"drivers/" + n for n in os.listdir(folder)
                if n.endswith(".py") and n != "__init__.py" and n[:-3] not in used}
    for other in port_names(app_dir):
        if other != name:
            for root, _dirs, files in os.walk(os.path.join(app_dir, PORTS_DIR, other)):
                out |= {os.path.relpath(os.path.join(root, f), app_dir).replace(os.sep, "/") for f in files if f.endswith(".py")}
    return out, off


