def cmd_reset_deps(args):
    c = load_config(args)
    repo = locate_repo(c["repo"])
    m5 = os.path.join(repo, "m5stack")
    lock = os.path.join(m5, "dependencies.lock")
    tracked = subprocess.run(["git", "-C", repo, "ls-files", "--error-unmatch", "m5stack/dependencies.lock"], capture_output=True).returncode == 0
    if tracked:
        raise BuildError("m5stack/dependencies.lock is part of the repository (git tracks it): it was put there on purpose, so it is not deleted.\n"
                         "  `git -C " + repo + " checkout -- m5stack/dependencies.lock` restores it if the build changed it.")
    removed = []
    for path in (lock, os.path.join(m5, "managed_components")):
        if os.path.isdir(path):
            shutil.rmtree(path)
            removed.append(path)
        elif os.path.isfile(path):
            os.remove(path)
            removed.append(path)
    build = os.path.join(m5, "build-" + c["base"] + BOARD_SUFFIX)
    if os.path.isdir(build):
        shutil.rmtree(build)
        removed.append(build)
    for r in removed:
        say("removed " + r)
    say("nothing to remove" if not removed else "the next build resolves the ESP-IDF components again (needs a network)")
    return 0


