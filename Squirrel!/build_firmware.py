def wrong_folder_hint(app_dir):
    if os.path.isfile(os.path.join(app_dir, "squirrel_app.py")):
        return None
    for root, dirs, files in os.walk(app_dir):
        dirs[:] = [d for d in dirs if d not in EXCLUDE_DIRS and not d.startswith(".")]
        if "squirrel_app.py" in files:
            return (f"squirrel_app.py is not in {app_dir} but in {root}.\n"
                    f"  build_firmware.py takes ITS OWN folder as the folder with the code: move it (and squirrel_boot.py, BUILD.md, device/) to {root}")
    return None


def prepare_sources(app_dir, verbose=True, exclude=(), prefer=None):
    hint = wrong_folder_hint(app_dir)
    if hint:
        raise BuildError(hint)
    sources = find_sources(app_dir, exclude)
    if not sources:
        raise BuildError(f"no .py files found in {app_dir}")
    staged, warnings = layout_for_firmware(sources, prefer)
    errors, more = check_imports(staged)
    if verbose:
        say(f"sources: {len(staged)} modules ({sum(1 for p in staged if p.startswith('screens/'))} of them screens)")
        for w in warnings + more:
            say("  warning: " + w)
        for e in errors:
            say("  ERROR: " + e)
    if errors:
        raise BuildError("the sources do not hang together (see ERROR lines above)")
    if "squirrel_boot.py" not in staged:
        raise BuildError("squirrel_boot.py is missing from the folder: /flash/main.py needs it")
    if "squirrel_app.py" not in staged:
        raise BuildError("squirrel_app.py is missing from the folder")
    return staged


