def find_sources(app_dir, extra_exclude=()):
    """[(relative path with '/', absolute path)] of every .py to freeze (extra_exclude: file names or relative paths to leave out)."""
    found = []
    for root, dirs, files in os.walk(app_dir):
        dirs[:] = sorted(d for d in dirs if d not in EXCLUDE_DIRS and not d.startswith("."))
        for name in sorted(files):
            if not name.endswith(".py") or name.startswith("test_") or name in EXCLUDE_FILES and root == app_dir:
                continue
            absolute = os.path.join(root, name)
            relative = os.path.relpath(absolute, app_dir).replace(os.sep, "/")
            if relative in extra_exclude or name in extra_exclude or relative in DOC_ONLY:
                continue
            found.append((relative, absolute))
    return found


_SCREEN_IMPORT = re.compile(r"""(?:^|\n)\s*(?:from|import)\s+screens\.(\w+)""")
_SCREEN_STRING = re.compile(r"""["']screens\.(\w+)["']""")


def screen_modules(sources):
    """Names X for which the code uses  screens.X  (an import, or a module name in a table of lazy screens)."""
    names = set()
    for _rel, absolute in sources:
        with open(absolute, encoding="utf-8") as f:
            text = f.read()
        names.update(_SCREEN_IMPORT.findall(text))
        names.update(_SCREEN_STRING.findall(text))
    return names


def _same_file(a, b):
    try:
        with open(a, "rb") as fa, open(b, "rb") as fb:
            return fa.read() == fb.read()
    except OSError:
        return False


def _describe(path):
    st = os.stat(path)
    return f"{path}  ({st.st_size} bytes, {time.strftime('%Y-%m-%d %H:%M:%S', time.localtime(st.st_mtime))})"


def layout_for_firmware(sources, prefer=None):
    """The same sources with the screens in a `screens/` package, whatever the folder looks like.

    A screen present BOTH flat and in screens/: identical copies are fine; different copies are an error (one of them
    is stale and it is not for a program to guess which) unless prefer is 'newer', 'flat' or 'screens'.
    Returns ({staged path: absolute path}, [warnings])."""
    wanted = screen_modules(sources)
    staged, warnings, dup = {}, [], {}
    by_rel = dict(sources)
    for rel, absolute in sources:
        base = rel.rsplit("/", 1)[-1][:-3]
        if "/" not in rel and base in wanted:
            target = "screens/" + base + ".py"
            if target in by_rel:
                dup[target] = (absolute, by_rel[target])
                continue
            staged[target] = absolute
        else:
            staged[rel] = absolute
    conflicts = []
    for target, (flat, nested) in sorted(dup.items()):
        if _same_file(flat, nested):
            staged[target] = nested
        elif prefer == "flat":
            staged[target] = flat
            warnings.append(f"{target[8:]} exists flat and in screens/ with DIFFERENT content: using the flat one (--prefer flat)")
        elif prefer == "screens":
            staged[target] = nested
            warnings.append(f"{target[8:]} exists flat and in screens/ with DIFFERENT content: using screens/ (--prefer screens)")
        elif prefer == "newer":
            newer = flat if os.path.getmtime(flat) >= os.path.getmtime(nested) else nested
            staged[target] = newer
            warnings.append(f"{target[8:]} exists flat and in screens/ with DIFFERENT content: using the newer, {newer}")
        else:
            conflicts.append(f"  {target[8:]} exists twice with different content:\n    flat   : {_describe(flat)}\n    screens: {_describe(nested)}")
    if conflicts:
        raise BuildError("Two different copies of the same screen module - one is stale, and the firmware must not freeze the wrong one:\n"
                         + "\n".join(conflicts) + "\n  Delete the stale file, or pass  --prefer newer|flat|screens.")
    for name in sorted(wanted):
        if "screens/" + name + ".py" not in staged:
            warnings.append(f"the code imports screens.{name}, but there is no {name}.py")
    return staged, warnings


def local_top_levels(staged):
    return {p.split("/")[0][:-3] if "/" not in p else p.split("/")[0] for p in staged}


def _local_module(staged, dotted):
    """True when `dotted` (a.b.c) is a module or a package folder among the staged sources."""
    path = dotted.replace(".", "/")
    return (path + ".py") in staged or any(rel.startswith(path + "/") for rel in staged)


def check_imports(staged):
    """([errors], [warnings]) from reading every import in the sources."""
    errors, warnings = [], []
    local = local_top_levels(staged) | {"sq_info"}        # sq_info.py is generated by this tool
    packages = {rel.split("/")[0] for rel in staged if "/" in rel}
    for rel, absolute in sorted(staged.items()):
        with open(absolute, encoding="utf-8") as f:
            text = f.read()
        try:
            tree = ast.parse(text, rel)
        except SyntaxError as e:
            errors.append(f"{rel}:{e.lineno}: {e.msg}")
            continue
        for node in ast.walk(tree):
            subs = ()
            if isinstance(node, ast.Import):
                names = [a.name for a in node.names]
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                names = [node.module]
                subs = [a.name for a in node.names]            # from drivers import m5_audio: m5_audio may be a module
            else:
                continue
            for dotted in names:
                top = dotted.split(".")[0]
                if top in packages:
                    # a module of one of the app's packages (screens, hw, drivers, ports ...) must be in this build -
                    # a port's file importing a module of another port, or of a feature it does not build, fails here
                    if "." in dotted and not _local_module(staged, dotted):
                        errors.append(f"{rel}:{node.lineno}: imports {dotted}, which is not in the sources (of this port)")
                    elif (dotted.replace(".", "/") + ".py") not in staged:       # a package: its names are modules
                        for name in subs:
                            if not _local_module(staged, dotted + "." + name):
                                errors.append(f"{rel}:{node.lineno}: imports {name} from {dotted}, which is not in the sources (of this port)")
                elif top in PC_ONLY:
                    errors.append(f"{rel}:{node.lineno}: imports '{top}', which exists on a PC only - this looks like a PC-side script, "
                                  f"not device code. Leave it out: \"exclude\": [\"{rel.rsplit('/', 1)[-1]}\"] in build_config.json, or --exclude")
                elif top not in local and top not in KNOWN_RUNTIME:
                    warnings.append(f"{rel}:{node.lineno}: imports '{top}' - not in the sources, not a known firmware module")
    return errors, sorted(set(warnings))


