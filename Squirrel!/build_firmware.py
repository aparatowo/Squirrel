#!/usr/bin/env python3
"""build_firmware.py - builds the firmware (.bin) with the Squirrel! code FROZEN into it.

Put this file in the folder that holds the app's .py files and run it there:

    python3 build_firmware.py --check          # look at the machine and the sources, change nothing
    python3 build_firmware.py --install-idf    # once, if there is no ESP-IDF 5.4.x: clone + install v5.4.2 (needs a network)
    python3 build_firmware.py --setup          # once: submodules, patches, mpy-cross, littlefs (needs quilt and a network)
    python3 build_firmware.py --stage-only     # collect the sources and check them with mpy-cross; no firmware
    python3 build_firmware.py                  # `make pack`  ->  dist/squirrel-<board>-<git>-<time>.bin  (a complete image)
    python3 build_firmware.py --target build   # only the application (micropython.bin): not flashable on its own
    python3 build_firmware.py --flash /dev/ttyACM0   # ... and flash it (only a complete image, at 0x0)
    python3 build_firmware.py --flash-image dist/squirrel-....bin [--flash /dev/ttyACM0]   # flash an image that is already built
    python3 build_firmware.py --setup-device /dev/ttyACM0   # prepare the device (main.py, UIFlow boot.py, boot option); --flash does it too
    python3 build_firmware.py --build-mpy-cross  # only gcc + make needed (no ESP-IDF, no quilt): builds the repo's mpy-cross
    python3 build_firmware.py --mpy            # no firmware: compile every module to .mpy in dist/mpy/ (a quick relief for RAM)
    python3 build_firmware.py --update-repo    # pull the latest changes in vendor/cardputer-adv-micropython
    python3 build_firmware.py --reset-deps     # forget the resolved ESP-IDF component versions (dependencies.lock, managed_components)
    python3 build_firmware.py --diagnose       # explain the last failed build from its log (.build/make.log)
    python3 build_firmware.py --clean          # remove what this tool generated
    python3 build_firmware.py --gen-port-config [--port NAME]   # port_config.py next to the sources, from ports/NAME/port.toml

What it does, in order:
  1. ensures vendor/cardputer-adv-micropython exists (clones it automatically on first run);
  2. collects the app's sources (every .py here, `screens/` as a package; a flat folder is fine too: the screen
     modules are recognised by how the code imports them); leaves out tests, tools, archive, verify_device.py ...
     and, for the port (--port, default cardputer_adv): the modules of features it does not build (features.toml),
     the drivers its port.toml does not name, the other ports' folders; port_config.py is generated from its port.toml;
  3. checks that every module the code imports exists and compiles with the SAME mpy-cross as the firmware;
  4. writes sq_info.py (build id, file list) into the set;
  5. makes a derived board  <base board>_Squirrel  inside the firmware repo: a copy of the base board whose manifest.py
     gets one more line, freeze("$(BOARD_DIR)/squirrel").  Nothing that exists in the repo is modified;
  6. puts the font (fonts/squirrel.vlw or squirrel.vlw) into the image's system file system: it is copied to
     m5stack/fs/system/common/font/ for the time of `make` and removed afterwards, and the device finds it at
     /system/common/font/squirrel.vlw (that partition is written by every flash, so the font cannot get lost);
  7. runs  make BOARD=<derived board> build  with the ESP-IDF environment loaded, finds the image and says
     whether it is a complete one (flash at 0x0).

Settings: command line, or build_config.json next to this file ({"repo": ..., "idf": ..., "base_board": ..., "port": ...}),
or the environment (SQUIRREL_FW_REPO, SQUIRREL_IDF).  Standard library only.
"""
