def wait_for_port(port, seconds=15):
    """Wait until the serial port exists again (an S3 re-appears on USB after a reset).  True if it does."""
    for _ in range(seconds * 2):
        if os.path.exists(port):
            return True
        time.sleep(0.5)
    return os.path.exists(port)


