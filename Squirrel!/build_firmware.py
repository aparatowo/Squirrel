def cmd_install_idf(args):
    dest = os.path.abspath(os.path.expanduser(args.install_idf))
    resume = os.path.isdir(os.path.join(dest, ".git"))
    if os.path.exists(dest) and os.listdir(dest) and not resume:
        raise BuildError(f"{dest} already exists and is not empty. Use --install-idf <another folder>, or --idf {dest} if it is the right one.")
    steps = []
    if resume:
        say(f"{dest} holds an earlier, unfinished installation: continuing it (what was downloaded is kept)")
    else:
        say(f"installing ESP-IDF {IDF_WANTED} into {dest}")
        steps.append(f'git clone --depth 1 --branch {IDF_WANTED} {IDF_URL} "{dest}"')
    steps.append(f'git -C "{dest}" submodule update --init --recursive --depth 1 --jobs 4 --progress')
    steps.append(f'cd "{dest}" && ./install.sh esp32s3')
    say("(a few hundred MB to 1-2 GB; the big libraries take minutes each. To see that it is alive: "
        f"`du -sh {dest}/.git/modules` in another terminal keeps growing. Ctrl-C is safe: run the same command again to continue)")
    for step in steps:
        if bash(step) != 0:
            raise BuildError(f"this step failed: {step}\n  Run the same command again: it continues where it stopped.")
    say(f"done. It is found automatically next time (or use --idf {dest}).")
    return 0


