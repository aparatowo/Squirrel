def ensure_repo(repo, update=False):
    """Clone the firmware repo into vendor/ if it is not there yet; with update=True, pull instead."""
    if os.path.isdir(os.path.join(repo, ".git")):
        if update:
            say(f"updating firmware repo at {repo}")
            code = subprocess.call(["git", "-C", repo, "pull", "--ff-only"])
            if code != 0:
                raise BuildError("git pull failed — check your network or resolve conflicts manually")
        else:
            say(f"firmware repo present at {repo} (use --update-repo to pull latest changes)")
        return
    parent = os.path.dirname(repo)
    os.makedirs(parent, exist_ok=True)
    say(f"cloning firmware repo into {repo} ...")
    say(f"  (first time only; ~100 MB; Ctrl-C is safe: run again to continue)")
    code = subprocess.call(["git", "clone", "--depth", "1", FIRMWARE_REPO_URL, repo])
    if code != 0:
        raise BuildError(
            f"git clone failed. Check your network connection and try again.\n"
            f"  Source : {FIRMWARE_REPO_URL}\n"
            f"  Target : {repo}\n"
            f"  Or set a different path with --repo, SQUIRREL_FW_REPO, or build_config.json."
        )
    say("clone done")


