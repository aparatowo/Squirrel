def read_log(path, limit=600_000):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            text = f.read()
        return text[-limit:]
    except OSError:
        return ""


def classify_image(path):
    try:
        with open(path, "rb") as f:
            head = f.read(0x8002)
    except OSError:
        return "other"
    if len(head) >= 0x8002 and head[0] == 0xE9 and head[0x8000:0x8002] == b"\xaa\x50":
        return "complete"
    return "partial" if head[:1] == b"\xe9" else "other"


def find_images(m5dir, since):
    out = []
    skip = ("/esp-idf/", "/managed_components/", "/CMakeFiles/", "/bootloader/", "/littlefs", "/.git/")
    for root, dirs, files in os.walk(m5dir):
        dirs[:] = [d for d in dirs if d not in (".git", "CMakeFiles", "managed_components")]
        for name in files:
            if not name.endswith(".bin"):
                continue
            path = os.path.join(root, name)
            if any(s in path + "/" for s in skip):
                continue
            try:
                st = os.stat(path)
            except OSError:
                continue
            if st.st_mtime >= since - 2:
                out.append((path, st.st_size, classify_image(path)))
    rank = {"complete": 0, "partial": 1, "other": 2}
    return sorted(out, key=lambda t: (rank[t[2]], -t[1]))


