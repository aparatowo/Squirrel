# tools/i18n/build.py - the translation tables lang/<code>.py from the translation files translations/<code>.tsv
#
#   python3 tools/i18n/build.py          (from the folder with squirrel_app.py)
# translations/<code>.tsv: a first line "en<TAB><code>", then one text per line - the English text, a tab, the
# translation; a line break inside a text is written \n, a tab \t.  An empty translation = shown in English.  The lines
# are kept sorted by the English text.  Each table lang/<code>.py is T = (english, translated, ...) sorted by the
# English text, which is what i18n._ searches.  Run check.py first: it says what is missing.
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(os.path.dirname(HERE))
LANG_DIR = os.path.join(APP, "translations")
OUT = os.path.join(APP, "lang")


def unescape(cell):
    return cell.replace("\\n", "\n").replace("\\t", "\t")


def escape(text):
    return text.replace("\t", "\\t").replace("\n", "\\n")


def read_file(path):
    """{english: translation} of one translation file."""
    out = {}
    with open(path, encoding="utf-8") as f:
        header = f.readline().rstrip("\n").split("\t")
        if len(header) != 2 or header[0] != "en":
            raise SystemExit("%s: the first line must be 'en<TAB><code>'" % path)
        for n, line in enumerate(f, 2):
            line = line.rstrip("\n")
            if not line:
                continue
            cells = line.split("\t")
            if len(cells) > 2:
                raise SystemExit("%s:%d: more than one tab" % (path, n))
            en = unescape(cells[0])
            if en in out:
                raise SystemExit("%s:%d: %r twice" % (path, n, en))
            out[en] = unescape(cells[1]) if len(cells) > 1 else ""
    return out


def languages():
    return sorted(f[:-4] for f in os.listdir(LANG_DIR) if f.endswith(".tsv"))


def read_catalog():
    """-> (languages, {english: {code: text}}) over every translation file."""
    langs = languages()
    rows = {}
    for code in langs:
        for en, tr in read_file(os.path.join(LANG_DIR, code + ".tsv")).items():
            rows.setdefault(en, {})[code] = tr
    for tr in rows.values():
        for code in langs:
            tr.setdefault(code, "")
    return langs, rows


def write_catalog(langs, rows):
    for code in langs:
        with open(os.path.join(LANG_DIR, code + ".tsv"), "w", encoding="utf-8") as f:
            f.write("en\t%s\n" % code)
            for en in sorted(rows):
                f.write("%s\t%s\n" % (escape(en), escape(rows[en].get(code, ""))))


def build():
    langs, rows = read_catalog()
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "__init__.py"), "w", encoding="utf-8") as f:
        f.write("# lang/ - the translation tables (generated by tools/i18n/build.py from translations/*.tsv; do not edit)\n")
    for code in langs:
        pairs = sorted((en, tr[code]) for en, tr in rows.items() if tr.get(code))
        with open(os.path.join(OUT, code + ".py"), "w", encoding="utf-8") as f:
            f.write("# lang/%s.py - generated by tools/i18n/build.py from translations/%s.tsv; do not edit\n" % (code, code))
            f.write("T = (\n")
            for en, tr in pairs:
                f.write("    %r, %r,\n" % (en, tr))
            f.write(")\n")
        print("lang/%s.py: %d texts" % (code, len(pairs)))


if __name__ == "__main__":
    build()
